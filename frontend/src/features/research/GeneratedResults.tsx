import { useEffect, useState } from 'react'
import { useSearchParams } from 'react-router-dom'
import { generatedDownloadUrl, getGeneratedReport, listGeneratedReports, type GeneratedAnswer, type GeneratedClaim, type GeneratedReport, type GeneratedReportSummary } from '../../api/client'
import { ExternalSource } from '../evidence/ExternalSource'
import { useWorkspace } from '../workspace/workspace'
import { locateQuote, type Position } from './tracker'

function Check({ ok, text }: { ok: boolean; text: string }) {
  return <li className={ok ? 'check-pass' : 'check-fail'}><span className="sr-only">{ok ? 'Passed: ' : 'Failed: '}</span><span aria-hidden="true">{ok ? '✓' : '✕'}</span> {text}</li>
}

function Passage({ text, quote }: { text: string; quote: string | null }) {
  const range = locateQuote(text, quote)
  if (!range) return <><blockquote className="passage">{text}</blockquote>{quote && <p className="record-dates">The exact excerpt couldn't be located. The full passage is shown.</p>}</>
  return <blockquote className="passage">{text.slice(0, range[0])}<mark className="cited-excerpt">{text.slice(range[0], range[1])}</mark>{text.slice(range[1])}</blockquote>
}

export function EvidenceBody({ answer, position, move, showClaim }: { answer: GeneratedAnswer; position: Position; move: (cite: number) => void; showClaim: (ordinal: number) => void }) {
  const claim: GeneratedClaim = answer.claims[position.claim]
  const citation = claim.citations[position.cite]
  const usable = citation.reference_valid
  const citedBy = answer.claims.filter(other => other.citations.some(item => item.passage_id === citation.passage_id))
  return <>
    <p className="record-dates">Web page · {citation.source_status ?? 'unknown status'}</p>
    <h3 className="inspector-source">{citation.source_title || 'Untitled source'}</h3>
    <ExternalSource url={citation.original_url} />
    {claim.citations.length > 1 && <div className="inspector-pager"><span>Citation {position.cite + 1} of {claim.citations.length} for finding {claim.ordinal}</span>
      <button type="button" className="button secondary small" disabled={position.cite === 0} onClick={() => move(position.cite - 1)}>Previous citation<span className="sr-only"> ({position.cite + 1} of {claim.citations.length})</span></button>
      <button type="button" className="button secondary small" disabled={position.cite === claim.citations.length - 1} onClick={() => move(position.cite + 1)}>Next citation<span className="sr-only"> ({position.cite + 1} of {claim.citations.length})</span></button></div>}
    {usable ? <Passage text={citation.passage_text} quote={citation.quoted_text} /> : <p role="alert" className="error-state">This reference couldn't be confirmed, so it isn't shown as evidence.</p>}
    <dl className="inspector-meta"><dt>Retrieved (UTC)</dt><dd>{citation.fetched_at || 'Unavailable'}</dd><dt>Location</dt><dd>Characters {citation.start_offset}–{citation.end_offset} of the saved text</dd></dl>
    <h4>Automatic checks</h4>
    <ul className="check-list">
      <Check ok={usable} text="Passage found in saved sources" />
      <Check ok={usable} text="Belongs to this investigation" />
      {citation.quote_valid === null ? <li>No quotation presented</li> : <Check ok={citation.quote_valid} text="Quotation matches saved text" />}
    </ul>
    <p className="inspector-caveat">These checks confirm the reference and wording. They don't confirm the claim is true. Semantic assessment isn't performed in this version, so a valid citation doesn't show that the source supports the claim.</p>
    <h4>Cited by</h4>
    <ul className="cited-by">{citedBy.map(other => <li key={other.ordinal}><button type="button" className="link-button" onClick={() => showClaim(other.ordinal)}>Finding {other.ordinal}: {other.claim_text}</button></li>)}</ul>
  </>
}

/** Model and source text render only as React text: nothing here can execute or load remotely. */
export function Findings() {
  const { research, openerRef } = useWorkspace()
  const [params, setParams] = useSearchParams()
  const { answer, answerLoaded } = research
  const evidence = params.get('evidence')
  if (!answerLoaded) return <p role="status">Loading findings…</p>
  if (!answer) return <div className="panel-empty"><h2>No findings yet</h2><p>Findings appear here after a research run completes. Each one links to the saved passages it cites.</p></div>
  return <section aria-labelledby="answer-title" className="findings">
    <h2 id="answer-title">Findings</h2>
    <p className="mode-note"><strong>{answer.mode === 'mock' ? 'SIMULATED · Not real research. ' : ''}AI-generated research aid. Verify important findings using original sources.</strong> {answer.provider_id === 'none' ? 'This partial report used no language model.' : `Generated by ${answer.provider_id} (${answer.model_id}), prompt ${answer.prompt_version}.`}</p>
    <p className="findings-summary">{answer.summary_text}</p>
    {answer.suppressed_citations > 0 && <p className="mode-note">{answer.suppressed_citations} citation(s) failed validation and were suppressed.</p>}
    {answer.claims.length === 0 ? <p>No findings were produced.</p> : <ol className="claim-list">{answer.claims.map(claim => <li key={claim.ordinal} id={`finding-${claim.ordinal}`} tabIndex={-1} className="claim-card">
      <div className="claim-head"><span className="claim-number">Finding {claim.ordinal}</span><span className={`chip ${claim.evidence_state === 'cited' ? 'chip-success badge-cited' : 'chip-warning badge-missing'}`}>{claim.evidence_state === 'cited' ? 'Cited' : 'Not established'}</span></div>
      <p>{claim.claim_text}</p>{claim.explanation && <p className="record-dates">{claim.explanation}</p>}
      {claim.citations.length > 0 && <div className="chip-row">{claim.citations.map(citation => {
        const current = evidence === citation.passage_id && params.get('finding') === String(claim.ordinal)
        return <button key={citation.passage_id} type="button" className={`citation-chip${current ? ' is-active' : ''}`} aria-pressed={current} aria-label={`Open evidence ${citation.display_id}`} onClick={event => { openerRef.current = event.currentTarget; setParams({ evidence: citation.passage_id, finding: String(claim.ordinal) }) }}>{citation.display_id}</button>
      })}</div>}
    </li>)}</ol>}
    {answer.limitations_text && <><h3>Limitations</h3><p>{answer.limitations_text}</p></>}
    {answer.needed_evidence_text && <><h3>Evidence still needed</h3><p>{answer.needed_evidence_text}</p></>}
  </section>
}

export function GeneratedReportViewer({ investigationId }: { investigationId: string }) {
  const [versions, setVersions] = useState<GeneratedReportSummary[]>()
  const [selected, setSelected] = useState<number>()
  const [report, setReport] = useState<GeneratedReport>()
  const [error, setError] = useState('')
  useEffect(() => {
    let active = true
    listGeneratedReports(investigationId).then(rows => { if (active) setVersions(rows) }).catch(() => { if (active) setError('Could not load saved results. Nothing was changed.') })
    return () => { active = false }
  }, [investigationId])
  const version = selected ?? versions?.[0]?.version_no
  useEffect(() => {
    let active = true
    if (version) getGeneratedReport(investigationId, version).then(value => { if (active) setReport(value) }).catch(() => { if (active) setError('This report version could not be opened or failed its integrity check.') })
    return () => { active = false }
  }, [investigationId, version])
  if (error) return <p role="alert" className="error-state">{error}</p>
  if (!versions) return <p role="status">Loading research reports…</p>
  if (!versions.length) return <p className="outline-muted">A research report is created when a research run completes.</p>
  return <>
    <label className="field">Report version<select value={version} onChange={event => setSelected(Number(event.target.value))}>{versions.map(item => <option key={item.version_no} value={item.version_no}>Version {item.version_no} — {new Date(item.created_at).toLocaleString()}</option>)}</select></label>
    {report && report.version_no === version && <article aria-label={`Research report version ${report.version_no}`}>
      {report.current_warnings.map(warning => <p key={warning} role="note" className="mode-note">{warning}</p>)}
      <p role="status">Report checked: {report.validation_summary.citations} references found, {report.validation_summary.quotations_matched} quotations match. {report.validation_summary.claims_not_established} claims are marked not established.</p>
      <p className="record-dates mono hash">SHA-256 {report.markdown_sha256}</p>
      <a className="button secondary" href={generatedDownloadUrl(investigationId, report.version_no)} download>Download report (.md)</a>
      <h4>Exact file contents</h4><pre className="report-preview" tabIndex={0}>{report.markdown_text}</pre>
    </article>}
  </>
}
