import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('manual workspace persists, conflicts safely and stays local', async ({ page, context, browser }) => {
  console.log(`Browser QA: Microsoft Edge ${browser.version()}`)
  const external: string[] = []
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await context.route('**/*', route => {
    if (new URL(route.request().url()).hostname !== '127.0.0.1') { external.push(route.request().url()); return route.abort() }
    return route.continue()
  })
  await page.goto('/')
  await page.getByRole('link', { name: 'New investigation', exact: true }).click()
  await page.getByLabel(/^Title/).fill('Synthetic local investigation')
  await page.getByLabel(/^Main research question/).fill('How can local research planning be verified?')
  await page.getByLabel(/^Description/).fill('Synthetic browser test data only.')
  expect((await new AxeBuilder({ page }).analyze()).violations.filter(v => ['serious', 'critical'].includes(v.impact ?? ''))).toEqual([])
  await page.getByRole('button', { name: 'Create investigation' }).click()
  await expect(page.getByRole('heading', { name: 'Investigation workspace' })).toBeVisible()
  await expect(page.getByText('Details saved locally', { exact: true })).toBeVisible()
  const address = page.url()
  await page.getByLabel(/^Title/).fill('Edited local investigation')
  await page.getByRole('button', { name: 'Save details' }).click()
  await expect(page.getByText('Details saved locally', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add step' }).click()
  await page.getByLabel(/^Sub-question 1/).fill('Identify local requirements')
  await page.getByLabel(/^Search-query note 1/).fill('local requirements notes')
  await page.getByRole('button', { name: 'Add step' }).click()
  await page.getByLabel(/^Sub-question 2/).fill('Check persistence')
  await page.getByRole('button', { name: 'Move up step 2' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel(/^Sub-question 1/)).toHaveValue('Check persistence')
  await page.getByRole('button', { name: 'Save plan' }).click()
  await expect(page.getByText('Plan saved locally · revision 1')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel(/^Title/)).toHaveValue('Edited local investigation')
  await expect(page.getByLabel(/^Sub-question 1/)).toHaveValue('Check persistence')
  await expect(page.getByLabel(/^Sub-question 2/)).toHaveValue('Identify local requirements')
  const other = await context.newPage()
  await other.goto(address)
  await expect(other.getByLabel(/^Sub-question 1/)).toHaveValue('Check persistence')
  await page.getByLabel(/^Sub-question 1/).fill('Newer saved step')
  await page.getByRole('button', { name: 'Save plan' }).click()
  await expect(page.getByText('Plan saved locally · revision 2')).toBeVisible()
  await other.getByLabel(/^Sub-question 1/).fill('Unsaved conflicting step')
  await other.getByRole('button', { name: 'Save plan' }).click()
  await expect(other.getByRole('alert')).toContainText('Newer changes exist')
  await expect(other.getByLabel(/^Sub-question 1/)).toHaveValue('Unsaved conflicting step')
  await other.close()
  await page.getByLabel(/^Sub-question 1/).fill('Temporary unsaved edit')
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Leave unsaved changes?')
  await page.getByRole('button', { name: 'Keep editing' }).click()
  await expect(page.getByLabel(/^Sub-question 1/)).toHaveValue('Temporary unsaved edit')
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Discard and leave' }).click()
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeFocused()
  await page.getByRole('link', { name: 'Dashboard', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Edited local investigation', exact: true })).toBeVisible()
  await page.getByRole('searchbox').fill('Edited local')
  await page.getByRole('link', { name: 'Edited local investigation', exact: true }).click()
  await expect(page.getByLabel(/^Sub-question 1/)).toHaveValue('Newer saved step')
  for (const width of [360, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect((await new AxeBuilder({ page }).analyze()).violations.filter(v => ['serious', 'critical'].includes(v.impact ?? ''))).toEqual([])
    if (width === 390 || width === 1440) await page.screenshot({ path: `test-results/workspace-${width}.png`, fullPage: true })
  }
  expect(await page.evaluate(() => Object.keys(localStorage).filter(key => /token/i.test(key)))).toEqual([])
  expect(external).toEqual([])
  expect(errors).toEqual([])
})

test('browser Back protects unsaved new investigation', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: 'New investigation', exact: true }).click()
  await page.getByLabel(/^Title/).fill('Unsaved draft')
  await page.goBack()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Keep editing' }).click()
  await expect(page.getByLabel(/^Title/)).toHaveValue('Unsaved draft')
})
